      ) order by x.created_at desc)
      from (
        select * from public.team_notes
        where author_user_id = p_user_id and status = 'active' and visibility = 'team'
          and public.keiko_is_team_staff(p_actor_user_id, team_id)
        order by created_at desc limit v_limit
      ) x join public.teams t on t.id = x.team_id
