create or replace function public.keiko_is_team_staff(p_user_id uuid, p_team_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $function$
  select exists (
    select 1
    from public.team_members tm
    join public.profiles p on p.id = tm.user_id and p.status = 'active'
    where tm.user_id = p_user_id
      and tm.team_id = p_team_id
      and tm.team_role in ('owner_admin', 'owner', 'manager', 'coach', 'advisor')
      and tm.admin_status = 'active'
      and (tm.access_ends_at is null or tm.access_ends_at > now())
  );
$function$;

create or replace function public.get_keiko_home_hub(p_team_id uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $function$
declare
  v_user_id uuid := auth.uid();
  v_user_type text;
  v_team_type text;
  v_is_staff boolean := false;
begin
  if v_user_id is null then raise exception 'auth_required' using errcode = '42501'; end if;
  select p.user_type into v_user_type from public.profiles p where p.id = v_user_id and p.status = 'active';
  if not found then raise exception 'profile_required' using errcode = '42501'; end if;

  if p_team_id is not null then
    if not exists (select 1 from public.team_members tm where tm.user_id = v_user_id and tm.team_id = p_team_id) then
      raise exception 'team_forbidden' using errcode = '42501';
    end if;
    select t.team_type into v_team_type from public.teams t where t.id = p_team_id;
    v_is_staff := public.keiko_is_team_staff(v_user_id, p_team_id);
  else
    v_is_staff := exists (
      select 1 from public.team_members tm
      where tm.user_id = v_user_id
        and public.keiko_is_team_staff(v_user_id, tm.team_id)
    );
  end if;

  return jsonb_build_object(
    'announcements', coalesce((
      select jsonb_agg(jsonb_build_object(
        'announcementId', a.id,
        'title', a.title,
        'body', a.body,
        'priority', a.priority,
        'actionLabel', coalesce(a.action_label, ''),
        'actionUrl', coalesce(a.action_url, ''),
        'startsAt', a.starts_at,
        'expiresAt', a.expires_at,
        'isRead', ar.user_id is not null
      ) order by
        case a.priority when 'urgent' then 1 when 'important' then 2 else 3 end,
        a.starts_at desc)
      from public.announcements a
      left join public.announcement_reads ar on ar.announcement_id = a.id and ar.user_id = v_user_id
      where a.status = 'published'
        and a.starts_at <= now()
        and (a.expires_at is null or a.expires_at > now())
        and (
          a.scope = 'all'
          or a.scope = v_user_type
          or (a.scope = 'team_admin' and v_is_staff)
          or (a.scope = 'team' and a.team_id = p_team_id)
        )
    ), '[]'::jsonb),
    'resources', coalesce((
      select jsonb_agg(jsonb_build_object(
        'resourceId', r.id,
        'resourceType', r.resource_type,
        'title', r.title,
        'description', r.description,
        'imageUrl', coalesce(r.image_url, ''),
        'destinationUrl', coalesce(r.destination_url, ''),
        'sortOrder', r.sort_order
      ) order by r.sort_order, r.created_at)
      from public.home_resources r
      where r.status = 'active'
        and (r.starts_at is null or r.starts_at <= now())
        and (r.expires_at is null or r.expires_at > now())
        and (r.audience = 'all' or r.audience = v_user_type or (r.audience = 'team_admin' and v_is_staff))
        and (r.team_type_filter is null or r.team_type_filter = v_team_type)
    ), '[]'::jsonb),
    'isTeamAdmin', v_is_staff,
    'userType', v_user_type,
    'teamType', coalesce(v_team_type, '')
  );
end;
$function$;

create or replace function public.mark_keiko_announcement_read(p_announcement_id uuid)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $function$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then raise exception 'auth_required' using errcode = '42501'; end if;
  if not exists (select 1 from public.announcements a where a.id = p_announcement_id and a.status = 'published') then
    raise exception 'announcement_not_found';
  end if;
  insert into public.announcement_reads (announcement_id, user_id)
  values (p_announcement_id, v_user_id)
  on conflict (announcement_id, user_id) do update set read_at = excluded.read_at;
  return jsonb_build_object('status', 'ok', 'announcementId', p_announcement_id);
end;
$function$;

create or replace function public.get_keiko_admin_access(p_actor_user_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $function$
declare
  v_operator boolean := public.keiko_is_operator(p_actor_user_id);
  v_teams jsonb;
begin
  if auth.role() <> 'service_role' then raise exception 'service_role_required' using errcode = '42501'; end if;

  if v_operator then
    select coalesce(jsonb_agg(jsonb_build_object(
      'teamId', t.id, 'teamName', t.team_name, 'teamType', t.team_type,
      'teamRole', 'operator', 'subscriptionStatus', coalesce(ts.status, 'pilot')
    ) order by t.team_name), '[]'::jsonb)
    into v_teams
    from public.teams t
    left join public.team_subscriptions ts on ts.team_id = t.id
    where t.status = 'active' and coalesce(t.category, '') <> 'personal';
    return jsonb_build_object('accessMode', 'operator', 'teams', v_teams);
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'teamId', t.id, 'teamName', t.team_name, 'teamType', t.team_type,
    'teamRole', tm.team_role, 'subscriptionStatus', coalesce(ts.status, 'pilot')
  ) order by t.team_name), '[]'::jsonb)
  into v_teams
  from public.team_members tm
  join public.teams t on t.id = tm.team_id and t.status = 'active'
  left join public.team_subscriptions ts on ts.team_id = t.id
  where tm.user_id = p_actor_user_id
    and tm.team_role in ('owner_admin', 'owner', 'manager', 'coach', 'advisor')
    and tm.admin_status = 'active'
    and (tm.access_ends_at is null or tm.access_ends_at > now())
    and coalesce(t.category, '') <> 'personal';

  if jsonb_array_length(v_teams) = 0 then raise exception 'admin_required' using errcode = '42501'; end if;
  return jsonb_build_object('accessMode', 'team_admin', 'teams', v_teams);
end;
$function$;

