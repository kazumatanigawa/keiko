create or replace function public.save_keiko_admin_announcement(
  p_actor_user_id uuid,
  p_announcement_id uuid,
  p_scope text,
  p_team_id uuid,
  p_title text,
  p_body text,
  p_priority text,
  p_action_label text,
  p_action_url text,
  p_starts_at timestamptz,
  p_expires_at timestamptz,
  p_status text
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $function$
declare
  v_id uuid := coalesce(p_announcement_id, gen_random_uuid());
  v_scope text := lower(btrim(coalesce(p_scope, 'all')));
  v_priority text := lower(btrim(coalesce(p_priority, 'normal')));
  v_status text := lower(btrim(coalesce(p_status, 'draft')));
begin
  if auth.role() <> 'service_role' or not public.keiko_is_operator(p_actor_user_id) then
    raise exception 'operator_required' using errcode = '42501';
  end if;
  if v_scope not in ('all', 'student', 'general', 'team_admin', 'team') then raise exception 'invalid_scope'; end if;
  if v_scope = 'team' and p_team_id is null then raise exception 'team_required'; end if;
  if v_priority not in ('normal', 'important', 'urgent') then raise exception 'invalid_priority'; end if;
  if v_status not in ('draft', 'published', 'archived') then raise exception 'invalid_status'; end if;
  if btrim(coalesce(p_title, '')) = '' or btrim(coalesce(p_body, '')) = '' then raise exception 'content_required'; end if;

  insert into public.announcements (
    id, author_user_id, scope, team_id, title, body, priority,
    action_label, action_url, starts_at, expires_at, status
  ) values (
    v_id, p_actor_user_id, v_scope, case when v_scope = 'team' then p_team_id else null end,
    btrim(p_title), btrim(p_body), v_priority, nullif(btrim(coalesce(p_action_label, '')), ''),
    nullif(btrim(coalesce(p_action_url, '')), ''), coalesce(p_starts_at, now()), p_expires_at, v_status
  )
  on conflict (id) do update set
    scope = excluded.scope, team_id = excluded.team_id, title = excluded.title,
    body = excluded.body, priority = excluded.priority, action_label = excluded.action_label,
    action_url = excluded.action_url, starts_at = excluded.starts_at,
    expires_at = excluded.expires_at, status = excluded.status, updated_at = now();

  return jsonb_build_object('status', 'ok', 'announcementId', v_id);
end;
$function$;

