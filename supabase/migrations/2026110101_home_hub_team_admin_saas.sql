    where tm.user_id = p_user_id and public.keiko_is_team_staff(p_actor_user_id, tm.team_id)
  ) then raise exception 'user_forbidden' using errcode = '42501'; end if;

  select * into v_profile from public.profiles where id = p_user_id;
  if not found then raise exception 'user_not_found'; end if;

  insert into public.team_admin_audit_events (actor_user_id, action, target_type, target_id, metadata)
  values (p_actor_user_id, 'view_user_detail', 'user', p_user_id::text, jsonb_build_object('source', 'admin_os'));

  return jsonb_build_object(
    'profile', jsonb_build_object(
      'userId', v_profile.id,
      'displayName', v_profile.display_name,
      'lastName', coalesce(v_profile.last_name, ''),
      'firstName', coalesce(v_profile.first_name, ''),
      'lastNameKana', coalesce(v_profile.last_name_kana, ''),
      'firstNameKana', coalesce(v_profile.first_name_kana, ''),
      'userType', v_profile.user_type,
      'appRole', 'player',
      'status', v_profile.status,
      'createdAt', v_profile.created_at
    ),
    'studentProfile', coalesce((
      select jsonb_build_object(
        'schoolName', coalesce(sp.school_name, ''), 'grade', coalesce(sp.grade, ''),
        'term', coalesce(sp.term, ''), 'roleLabel', coalesce(sp.role_label, '')
      ) from public.student_profiles sp where sp.user_id = p_user_id
    ), '{}'::jsonb),
    'generalProfile', '{}'::jsonb,
    'teams', coalesce((
      select jsonb_agg(jsonb_build_object(
        'teamId', t.id, 'teamName', t.team_name, 'teamType', t.team_type,
        'teamRole', tm.team_role, 'isPersonal', false
      ) order by t.team_name)
      from public.team_members tm join public.teams t on t.id = tm.team_id
      where tm.user_id = p_user_id and public.keiko_is_team_staff(p_actor_user_id, t.id)
    ), '[]'::jsonb),
    'logs', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', x.id, 'teamId', x.team_id, 'teamName', t.team_name,
        'practiceDate', x.practice_date, 'condition', x.condition,
        'learning', x.learning, 'nextAction', x.next_action, 'goodNew', x.good_new,
        'memo', coalesce(x.memo, ''), 'visibility', x.visibility, 'createdAt', x.created_at
      ) order by x.practice_date desc, x.created_at desc)
      from (
        select * from public.practice_logs
        where user_id = p_user_id and visibility = 'team' and public.keiko_is_team_staff(p_actor_user_id, team_id)
        order by practice_date desc, created_at desc limit v_limit
      ) x join public.teams t on t.id = x.team_id
    ), '[]'::jsonb),
    'notes', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', x.id, 'teamId', x.team_id, 'teamName', t.team_name,
        'title', x.title, 'body', x.body, 'visibility', x.visibility,
