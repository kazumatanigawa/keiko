create or replace function public.get_keiko_scoped_admin_users(
  p_actor_user_id uuid,
  p_query text default '',
  p_team_id uuid default null,
  p_status text default '',
  p_limit integer default 50,
  p_offset integer default 0
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $function$
declare
  v_limit integer := greatest(1, least(coalesce(p_limit, 50), 100));
  v_offset integer := greatest(0, coalesce(p_offset, 0));
  v_query text := btrim(coalesce(p_query, ''));
begin
  if auth.role() <> 'service_role' then raise exception 'service_role_required' using errcode = '42501'; end if;
  if public.keiko_is_operator(p_actor_user_id) then
    return public.get_keiko_admin_users(p_actor_user_id, p_query, p_team_id, p_status, p_limit, p_offset);
  end if;
  if p_team_id is not null and not public.keiko_is_team_staff(p_actor_user_id, p_team_id) then
    raise exception 'team_forbidden' using errcode = '42501';
  end if;
  if not exists (select 1 from public.team_members tm where tm.user_id = p_actor_user_id and public.keiko_is_team_staff(p_actor_user_id, tm.team_id)) then
    raise exception 'admin_required' using errcode = '42501';
  end if;

  return jsonb_build_object(
    'total', (
      select count(distinct p.id)
      from public.profiles p
      join public.team_members target_tm on target_tm.user_id = p.id
      where public.keiko_is_team_staff(p_actor_user_id, target_tm.team_id)
        and (p_team_id is null or target_tm.team_id = p_team_id)
        and (nullif(p_status, '') is null or p.status = p_status)
        and (v_query = '' or p.display_name ilike '%' || v_query || '%')
    ),
    'users', coalesce((
      select jsonb_agg(jsonb_build_object(
        'userId', u.id,
        'displayName', u.display_name,
        'lastNameKana', coalesce(u.last_name_kana, ''),
        'firstNameKana', coalesce(u.first_name_kana, ''),
        'userType', u.user_type,
        'appRole', 'player',
        'status', u.status,
        'createdAt', u.created_at,
        'practiceLogCount', u.practice_log_count,
        'noteCount', u.note_count,
        'commentCount', u.comment_count,
        'latestActivityAt', u.latest_activity_at,
        'teams', u.teams
      ) order by u.latest_activity_at desc nulls last, u.display_name)
      from (
        select distinct on (p.id)
          p.id, p.display_name, p.last_name_kana, p.first_name_kana, p.user_type, p.status, p.created_at,
          (select count(*) from public.practice_logs pl where pl.user_id = p.id and pl.visibility = 'team' and public.keiko_is_team_staff(p_actor_user_id, pl.team_id)) as practice_log_count,
          (select count(*) from public.team_notes n where n.author_user_id = p.id and n.status = 'active' and n.visibility = 'team' and public.keiko_is_team_staff(p_actor_user_id, n.team_id)) as note_count,
          (select count(*) from public.team_note_comments c where c.author_user_id = p.id and c.status = 'active' and public.keiko_is_team_staff(p_actor_user_id, c.team_id)) as comment_count,
          greatest(
            coalesce((select max(pl.created_at) from public.practice_logs pl where pl.user_id = p.id and pl.visibility = 'team' and public.keiko_is_team_staff(p_actor_user_id, pl.team_id)), '-infinity'::timestamptz),
            coalesce((select max(n.created_at) from public.team_notes n where n.author_user_id = p.id and n.status = 'active' and n.visibility = 'team' and public.keiko_is_team_staff(p_actor_user_id, n.team_id)), '-infinity'::timestamptz)
          ) as latest_activity_at,
          coalesce((
            select jsonb_agg(jsonb_build_object(
              'teamId', t.id, 'teamName', t.team_name, 'teamType', t.team_type,
              'teamRole', member_tm.team_role, 'isPersonal', false
            ) order by t.team_name)
            from public.team_members member_tm
            join public.teams t on t.id = member_tm.team_id
            where member_tm.user_id = p.id and public.keiko_is_team_staff(p_actor_user_id, t.id)
          ), '[]'::jsonb) as teams
        from public.profiles p
        join public.team_members target_tm on target_tm.user_id = p.id
        where public.keiko_is_team_staff(p_actor_user_id, target_tm.team_id)
          and (p_team_id is null or target_tm.team_id = p_team_id)
          and (nullif(p_status, '') is null or p.status = p_status)
          and (v_query = '' or p.display_name ilike '%' || v_query || '%')
        order by p.id, latest_activity_at desc nulls last
        limit v_limit offset v_offset
      ) u
    ), '[]'::jsonb)
  );
end;
$function$;

